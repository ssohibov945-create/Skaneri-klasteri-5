  function normalize(str) {
    if (!str) return '';
    return String(str)
      .toLowerCase()
      .replace(/[ҳҳ]/g, 'х')
      .replace(/[ққ]/g, 'к')
      .replace(/[ғғ]/g, 'г')
      .replace(/[ҷҷ]/g, 'ч')
      .replace(/[ӣй]/g, 'и')
      .replace(/[ӯу]/g, 'у')
      .replace(/[әэ]/g, 'е')
      .replace(/ё/g, 'е')
      .replace(/[ъь]/g, '')
      .replace(/[^\wа-яёa-z0-9\s§]/gi, ' ')
      .replace(/\s+/g, ' ')
      .trim();
  }

  function searchBook(bookId, query) {
    const book = books.find(b => b.id === bookId);
    if (!book || !query || !query.trim()) return [];
    const q = normalize(query);
    const tokens = q.split(/\s+/).filter(t => t.length > 1);
    if (!tokens.length) return [];

    const results = [];
    for (const item of book.toc) {
      const hay = normalize(item.title + ' ' + (item.chapter || ''));
      let score = 0;
      let matched = 0;
      for (const t of tokens) {
        if (hay.includes(t)) {
          matched++;
          score += t.length;
          if (hay.indexOf(t) === 0 || hay.includes(' ' + t)) score += 5;
        }
      }
      if (matched === tokens.length) {
        results.push({ ...item, score: score + 100, bookId });
      } else if (matched > 0) {
        results.push({ ...item, score, bookId });
      }
    }
    results.sort((a, b) => b.score - a.score);
    return results.slice(0, 30);
  }

  function getBook(id) {
    return books.find(b => b.id === id) || null;
  }

  function t(book, field, lang) {
    const v = book[field];
    if (typeof v === 'object' && v) return v[lang] || v.tg || v.ru || '';
    return v || '';
  }

  global.BooksData = { books, searchBook, getBook, normalize, t };
